type pdfDoc struct {
	*fpdf.Fpdf
	tr func(string) string
}

func newPDF() *pdfDoc {
	p := fpdf.New("P", "mm", "Letter", "")
	p.SetMargins(8, 8, 8)
	p.SetAutoPageBreak(false, 8)
	p.SetCreator("EHR Billing", true)

	return &pdfDoc{Fpdf: p, tr: p.UnicodeTranslatorFromDescriptor("")}
}

func (p *pdfDoc) text(x, y float64, size float64, style, value string) {
	p.SetFont("Helvetica", style, size)
	p.Text(x, y, p.tr(value))
}

// box draws a labeled field: a small item label in the corner and the value
// beneath it, clipped to the box width.
func (p *pdfDoc) box(x, y, w, h float64, label, value string) {
	p.SetDrawColor(120, 120, 120)
	p.Rect(x, y, w, h, "D")

	p.SetTextColor(90, 90, 90)
	p.text(x+0.8, y+2.6, 5.5, "", label)

	p.SetTextColor(0, 0, 0)
	p.SetFont("Helvetica", "B", 8.5)

	lines := strings.Split(value, "\n")
	for i, line := range lines {
		ty := y + 6.5 + float64(i)*3.6
		if ty > y+h-0.5 {
			break
		}
		p.Text(x+1.2, ty, p.tr(p.fit(line, w-2.4)))
	}
}

// fit truncates text so it fits within width w at the current font.
func (p *pdfDoc) fit(value string, w float64) string {
	for value != "" && p.GetStringWidth(p.tr(value)) > w {
		value = value[:len(value)-1]
	}

	return value
}

func (p *pdfDoc) output() ([]byte, string, error) {
	var buf bytes.Buffer

	if err := p.Output(&buf); err != nil {
		return nil, "", err
	}

	sum := sha256.Sum256(buf.Bytes())

	return buf.Bytes(), hex.EncodeToString(sum[:]), nil
}

func upper(value string) string {
	return strings.ToUpper(value)
}

// mmddyyyy formats an ISO date as MM DD YYYY (CMS-1500 style).
func mmddyyyy(iso string) string {
	t, err := time.Parse("2006-01-02", iso)
	if err != nil {
		return ""
	}

	return t.Format("01 02 2006")
}

func check(selected bool) string {
	if selected {
		return "[X]"
	}

	return "[ ]"
}

func personName(last, first, middle string) string {
	name := upper(last)
	if first != "" {
		name += ", " + upper(first)
	}
	if middle != "" {
		name += " " + upper(middle[:1])
	}

	return name
}

func addressLines(a SnapshotAddress, phone string) string {
	street := upper(a.Address1)
	if a.Address2 != "" {
		street += " " + upper(a.Address2)
	}

	out := street + "\n" + upper(a.City) + "  " + upper(a.State) + "  " + a.Zip
	if phone != "" {
		out += "\nPHONE " + phone
	}

	return out
}

func moneyParts(cents int64) string {
	return fmt.Sprintf("%d %02d", cents/100, cents%100)
}

