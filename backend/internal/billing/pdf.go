type superbillLine struct {
	ChargeID       string   `json:"charge_id"`
	DateOfService  string   `json:"date_of_service"`
	ServiceCode    string   `json:"service_code"`
	Description    string   `json:"description"`
	Modifiers      []string `json:"modifiers"`
	Units          int      `json:"units"`
	PlaceOfService string   `json:"place_of_service"`
	Diagnoses      string   `json:"diagnoses"`
	Fee            string   `json:"fee"`
	Paid           string   `json:"paid"`
	Clinician      string   `json:"clinician"`
	ClinicianNPI   string   `json:"clinician_npi"`
}

type superbillData struct {
	Practice    SnapshotPractice `json:"practice"`
	Patient     SnapshotPerson   `json:"patient"`
	Diagnoses   []ClaimDiagnosis `json:"diagnoses"`
	Lines       []superbillLine  `json:"lines"`
	TotalFees   string           `json:"total_fees"`
	TotalPaid   string           `json:"total_paid"`
	GeneratedAt string           `json:"generated_at"`
}

func renderSuperbill(d superbillData) ([]byte, string, error) {
	p := newPDF()
	p.AddPage()
	p.SetTextColor(0, 0, 0)

	p.text(8, 14, 15, "B", "SUPERBILL / STATEMENT OF SERVICES")
	p.text(8, 19, 7, "", "Itemized record of services for submission to your insurance. This is not a bill from your insurer.")

	p.box(8, 24, 100, 24, "PROVIDER / PRACTICE",
		d.Practice.Name+"\n"+addressLines(d.Practice.Address, d.Practice.Phone)+
			fmt.Sprintf("\nNPI %s   TAX ID (%s) %s", d.Practice.NPI, upper(d.Practice.TaxIDType), d.Practice.TaxID))
	p.box(108, 24, 100, 24, "PATIENT",
		personName(d.Patient.LastName, d.Patient.FirstName, d.Patient.MiddleName)+
			"\nDOB "+mmddyyyy(d.Patient.DateOfBirth)+"\n"+addressLines(d.Patient.Address, ""))

	y := 52.0
	p.text(8, y, 9, "B", "DIAGNOSES")
	y += 4
	for _, dx := range d.Diagnoses {
		p.text(10, y, 8, "", fmt.Sprintf("%s.  %s  %s", dx.Letter, dx.ICD10Code, dx.Description))
		y += 4
	}

	y += 3
	columns := []struct {
		label string
		w     float64
	}{
		{"DATE", 20}, {"CODE", 18}, {"MOD", 12}, {"DESCRIPTION", 44}, {"POS", 10}, {"DX", 10},
		{"UNITS", 11}, {"PROVIDER (NPI)", 43}, {"FEE", 16}, {"PAID", 16},
	}

	p.SetFillColor(235, 235, 235)
	p.SetFont("Helvetica", "B", 7)
	x := 8.0
	for _, c := range columns {
		p.SetXY(x, y)
		p.CellFormat(c.w, 6, c.label, "1", 0, "L", true, 0, "")
		x += c.w
	}
	y += 6

	p.SetFont("Helvetica", "", 7)

	for _, l := range d.Lines {
		if y > 255 {
			p.AddPage()
			y = 12
		}

		cells := []string{
			l.DateOfService, l.ServiceCode, strings.Join(l.Modifiers, " "), l.Description, l.PlaceOfService,
			l.Diagnoses, fmt.Sprint(l.Units), l.Clinician + " (" + l.ClinicianNPI + ")", "$" + l.Fee, "$" + l.Paid,
		}

		x = 8.0
		for i, c := range columns {
			p.SetXY(x, y)
			align := "L"
			if i >= 8 {
				align = "R"
			}
			p.CellFormat(c.w, 6, p.tr(p.fit(cells[i], c.w-1.5)), "1", 0, align, false, 0, "")
			x += c.w
		}
		y += 6
	}

	y += 4
	p.text(150, y, 9, "B", "Total fees: $"+d.TotalFees)
	p.text(150, y+5, 9, "B", "Total paid: $"+d.TotalPaid)

	p.SetTextColor(70, 70, 70)
	p.text(8, 272, 6.5, "", "Generated "+d.GeneratedAt+". Provider signature on file.")

	return p.output()
}
