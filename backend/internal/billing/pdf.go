// cms1500Data is everything the CMS-1500 layout prints. It comes entirely
// from the claim snapshot and snapshotted claim lines.
type cms1500Data struct {
	ClaimNumber   string
	Snapshot      ClaimSnapshot
	Lines         []ClaimLine
	Diagnoses     []ClaimDiagnosis
	FrequencyCode string
	OriginalRef   string
	AmountPaid    int64
	GeneratedAt   time.Time
}

const cms1500Disclaimer = "CMS-1500 (02/12)-compatible field layout generated by this application. " +
	"This is NOT the official red OCR CMS-1500 form; payers that require the official form " +
	"should receive this data printed on pre-printed CMS-1500 stock."

const cmsLinesPerPage = 6

func frequencyCodeFor(resubmissionType string) string {
	switch resubmissionType {
	case "amended":
		return "7"
	case "void":
		return "8"
	}

	return "1"
}

// renderCMS1500 renders a claim on as many pages as needed (6 lines per
// page). Each page carries the totals for its own lines.
func renderCMS1500(d cms1500Data) ([]byte, string, int, error) {
	p := newPDF()
	s := d.Snapshot

	pages := (len(d.Lines) + cmsLinesPerPage - 1) / cmsLinesPerPage
	if pages == 0 {
		pages = 1
	}

	for page := 0; page < pages; page++ {
		p.AddPage()

		start := page * cmsLinesPerPage
		end := min(start+cmsLinesPerPage, len(d.Lines))
		lines := d.Lines[start:end]

		// ---- Header / carrier block
		p.SetTextColor(0, 0, 0)
		p.text(8, 12, 12, "B", "HEALTH INSURANCE CLAIM FORM")
		p.text(8, 16, 6.5, "", "CMS-1500 (02/12) COMPATIBLE FIELD LAYOUT - NOT AN OFFICIAL CMS FORM")

		carrier := upper(s.Payer.Name) + "\n" + addressLines(s.Payer.Address, "")
		p.box(128, 8, 80, 18, "CARRIER", carrier)

		y := 28.0

		// ---- Items 1 / 1a
		t := s.Payer.InsuranceType
		insType := fmt.Sprintf(
			"%s MEDICARE   %s MEDICAID   %s TRICARE   %s CHAMPVA\n%s GROUP HEALTH PLAN   %s FECA BLK LUNG   %s OTHER",
			check(t == "medicare"), check(t == "medicaid"), check(t == "tricare"), check(t == "champva"),
			check(t == "group_health_plan"), check(t == "feca_black_lung"), check(t == "other" || t == ""),
		)
		p.box(8, y, 130, 12, "1. INSURANCE TYPE", insType)
		p.box(138, y, 70, 12, "1a. INSURED'S I.D. NUMBER", upper(s.Insured.MemberID))
		y += 12

		// ---- Items 2 / 3 / 4
		p.box(8, y, 80, 10, "2. PATIENT'S NAME (Last, First, MI)", personName(s.Patient.LastName, s.Patient.FirstName, s.Patient.MiddleName))
		p.box(88, y, 50, 10, "3. PATIENT'S BIRTH DATE / SEX", mmddyyyy(s.Patient.DateOfBirth)+"   "+s.Patient.Sex)
		p.box(138, y, 70, 10, "4. INSURED'S NAME (Last, First, MI)", personName(s.Insured.LastName, s.Insured.FirstName, s.Insured.MiddleName))
		y += 10

		// ---- Items 5 / 6 / 7
		rel := s.Insured.Relationship
		relationship := fmt.Sprintf("%s SELF  %s SPOUSE\n%s CHILD  %s OTHER",
			check(rel == "self"), check(rel == "spouse"), check(rel == "child"), check(rel == "other"))
		p.box(8, y, 80, 17, "5. PATIENT'S ADDRESS", addressLines(s.Patient.Address, s.Patient.Phone))
		p.box(88, y, 50, 17, "6. PATIENT RELATIONSHIP TO INSURED", relationship)
		p.box(138, y, 70, 17, "7. INSURED'S ADDRESS", addressLines(s.Insured.Address, ""))
		y += 17

		// ---- Items 9 / 10 / 11
		var other SnapshotOtherInsurance
		hasOther := len(s.OtherInsurance) > 0
		if hasOther {
			other = s.OtherInsurance[0]
		}

		p.box(8, y, 80, 10, "9. OTHER INSURED'S NAME", upper(other.InsuredName))
		p.box(88, y, 50, 10, "10. CONDITION RELATED TO: EMPL / AUTO / OTHER", "NO / NO / NO")
		p.box(138, y, 70, 10, "11. INSURED'S POLICY GROUP OR FECA NUMBER", upper(s.Insured.PolicyGroup))
		y += 10

		otherPolicy := ""
		if hasOther {
			otherPolicy = upper(other.MemberID + " " + other.PolicyGroup)
		}
		p.box(8, y, 80, 10, "9a. OTHER INSURED'S POLICY OR GROUP NUMBER", otherPolicy)
		p.box(88, y, 50, 10, "10d. CLAIM CODES", "")
		p.box(138, y, 70, 10, "11a. INSURED'S DATE OF BIRTH / SEX", mmddyyyy(s.Insured.DateOfBirth)+"   "+s.Insured.Sex)
		y += 10

		p.box(8, y, 80, 10, "9d. OTHER INSURANCE PLAN NAME", upper(other.PayerName))
		p.box(88, y, 50, 10, "11c. INSURANCE PLAN NAME", upper(s.Insured.PlanName))
		anotherPlan := "NO"
		if hasOther {
			anotherPlan = "YES"
		}
		p.box(138, y, 70, 10, "11d. IS THERE ANOTHER HEALTH BENEFIT PLAN?", anotherPlan)
		y += 10

		// ---- Items 12 / 13
		signature := ""
		if s.Insured.SignatureOnFile {
			signature = "SIGNATURE ON FILE"
		}
		p.box(8, y, 130, 9, "12. PATIENT'S OR AUTHORIZED PERSON'S SIGNATURE", signature)
		p.box(138, y, 70, 9, "13. INSURED'S OR AUTHORIZED PERSON'S SIGNATURE", signature)
		y += 9

		// ---- Items 14-20 (not tracked by this application)
		p.box(8, y, 50, 9, "14. DATE OF CURRENT ILLNESS", "")
		p.box(58, y, 40, 9, "15. OTHER DATE", "")
		p.box(98, y, 50, 9, "16. DATES UNABLE TO WORK", "")
		p.box(148, y, 60, 9, "18. HOSPITALIZATION DATES", "")
		y += 9
		p.box(8, y, 90, 9, "17. NAME OF REFERRING PROVIDER", "")
		p.box(98, y, 70, 9, "19. ADDITIONAL CLAIM INFORMATION", "")
		p.box(168, y, 40, 9, "20. OUTSIDE LAB?", "NO")
		y += 9

		// ---- Items 21 / 22 / 23
		var dx strings.Builder
		for i, diagnosis := range d.Diagnoses {
			if i > 0 && i%4 == 0 {
				dx.WriteString("\n")
			} else if i > 0 {
				dx.WriteString("    ")
			}
			fmt.Fprintf(&dx, "%s. %s", diagnosis.Letter, strings.ReplaceAll(diagnosis.ICD10Code, ".", ""))
		}
		p.box(8, y, 130, 16, "21. DIAGNOSIS OR NATURE OF ILLNESS OR INJURY (ICD Ind. 0)", dx.String())

		resubmission := ""
		if d.FrequencyCode != "1" {
			resubmission = d.FrequencyCode + "    " + upper(d.OriginalRef)
		}
		p.box(138, y, 70, 8, "22. RESUBMISSION CODE / ORIGINAL REF. NO.", resubmission)

		authorization := ""
		for _, l := range d.Lines {
			if l.PriorAuthorizationCode != "" {
				authorization = upper(l.PriorAuthorizationCode)
				break
			}
		}
		p.box(138, y+8, 70, 8, "23. PRIOR AUTHORIZATION NUMBER", authorization)
		y += 16

		// ---- Item 24 service lines
		headers := []struct {
			label string
			w     float64
		}{
			{"24A. DATE(S) OF SERVICE", 38}, {"B. POS", 12}, {"C. EMG", 10}, {"D. CPT/HCPCS  MODIFIER", 42},
			{"E. DX PTR", 16}, {"F. $ CHARGES", 26}, {"G. UNITS", 14}, {"H. EPSDT", 10}, {"I. QUAL", 10}, {"J. RENDERING NPI", 22},
		}

		x := 8.0
		for _, h := range headers {
			p.box(x, y, h.w, 6, h.label, "")
			x += h.w
		}
		y += 6

		var pageTotal int64

		for i := 0; i < cmsLinesPerPage; i++ {
			var cells []string

			if i < len(lines) {
				l := lines[i]
				total := mustCents(l.LineTotal)
				pageTotal += total

				code := upper(l.ServiceCode)
				if len(l.Modifiers) > 0 {
					code += "  " + strings.Join(l.Modifiers, " ")
				}

				cells = []string{
					mmddyyyy(l.DateOfService) + "  " + mmddyyyy(l.DateOfService),
					l.PlaceOfService, "", code, l.DiagnosisPointers, moneyParts(total),
					fmt.Sprint(l.Units), "", "NPI", l.RenderingNPI,
				}
			} else {
				cells = make([]string, len(headers))
			}

			x = 8.0
			for j, h := range headers {
				p.box(x, y, h.w, 8, "", cells[j])
				x += h.w
			}
			y += 8
		}

		// ---- Items 25-30
		taxType := fmt.Sprintf("%s SSN %s EIN", check(s.Practice.TaxIDType == "ssn"), check(s.Practice.TaxIDType != "ssn"))
		p.box(8, y, 52, 10, "25. FEDERAL TAX I.D. NUMBER", s.Practice.TaxID+"  "+taxType)
		p.box(60, y, 40, 10, "26. PATIENT'S ACCOUNT NO.", upper(s.Patient.AccountNumber))
		p.box(100, y, 28, 10, "27. ACCEPT ASSIGNMENT?", "YES")
		p.box(128, y, 28, 10, "28. TOTAL CHARGE", moneyParts(pageTotal))

		paid := ""
		if d.AmountPaid > 0 && page == 0 {
			paid = moneyParts(d.AmountPaid)
		}
		p.box(156, y, 26, 10, "29. AMOUNT PAID", paid)
		p.box(182, y, 26, 10, "30. RSVD FOR NUCC USE", "")
		y += 10

		// ---- Items 31-33
		p.box(8, y, 60, 22, "31. SIGNATURE OF PHYSICIAN OR SUPPLIER", "SIGNATURE ON FILE\nDATE "+d.GeneratedAt.Format("01 02 2006"))
		p.box(68, y, 70, 22, "32. SERVICE FACILITY LOCATION / 32a. NPI",
			upper(s.Practice.Name)+"\n"+addressLines(s.Practice.Address, "")+"\nNPI "+s.Practice.NPI)
		p.box(138, y, 70, 22, "33. BILLING PROVIDER INFO & PH # / 33a. NPI",
			upper(s.Practice.Name)+"\n"+addressLines(s.Practice.Address, s.Practice.Phone)+"\nNPI "+s.Practice.NPI)
		y += 24

		// ---- Footer
		p.SetTextColor(70, 70, 70)
		p.text(8, y, 6.5, "", fmt.Sprintf("Claim %s  |  Page %d of %d  |  Generated %s",
			d.ClaimNumber, page+1, pages, d.GeneratedAt.Format("2006-01-02 15:04 MST")))
		p.SetXY(8, y+1.5)
		p.SetFont("Helvetica", "", 6)
		p.MultiCell(200, 2.8, p.tr(cms1500Disclaimer), "", "L", false)
	}

	bytes, sum, err := p.output()

	return bytes, sum, pages, err
}

